## Generate the shared Poisson real-data problem (congress109) consumed by
## downstream solvers. Follows the same convention as sim-real-problem.jl for
## the logistic problems: pre-standardised dense X, integer-valued y, lambda
## on the (1/n) * sum(loss) + lambda * ||beta||_1 scale.
##
## Dataset: congress109Counts from R's textir (Taddy, AoAS 2015), n = 529
## speakers (107th-109th US Congress) x 1000 political phrases (uni-/bigrams
## post-stemming). Construction (Taddy's distributed multinomial regression):
## drop one mid-frequency target phrase from the vocabulary, regress its
## count on the remaining 999 phrase counts. This is the canonical
## construction motivating Poisson lasso -- an independent-Poisson
## approximation to the document-level multinomial-over-vocabulary -- and
## congress109's phrase-mean-count distribution puts the response in the
## μ₀ ∈ [2, 12] regime where the bounded-Hessian / unbounded-Hessian
## distinction is operational (in contrast to we8thereCounts, whose
## bigrams have mean counts below 0.1 and put any Poisson lasso in a
## near-degenerate Bernoulli regime).
##
## Target phrase selection: deterministic. Pick the phrase with the highest
## total count -- this lands at ybar ~ 12, in the μ₀ ~ 10 regime where the
## Poisson Newton step `delta = ybar - 1` at cold start substantially
## overshoots the exact intercept `log(ybar) ~ 2.5`, so the Armijo guard on
## the intercept update has real work to do (the synthetic cold-start
## experiment in sim-cold-start-poisson.jl starts its sweep at exactly
## μ₀ = 10 for the same reason). The chosen phrase is recorded in
## meta.json for reproducibility.

suppressPackageStartupMessages({
  library(textir)
  library(Matrix)
  library(jsonlite)
})

get_script_dir <- function() {
  args <- commandArgs(trailingOnly = FALSE)
  flag <- "--file="
  match <- grep(flag, args)
  if (length(match) > 0) {
    normalizePath(dirname(sub(flag, "", args[match])))
  } else if (!is.null(sys.frame(1)$ofile)) {
    normalizePath(dirname(sys.frame(1)$ofile))
  } else {
    normalizePath(".")
  }
}
root <- normalizePath(file.path(get_script_dir(), ".."))

data(congress109, package = "textir")
# congress109Counts is already a dgCMatrix; use it directly.
counts <- congress109Counts
n_total <- nrow(counts)
p_total <- ncol(counts)
cat(sprintf("congress109Counts: %d speakers x %d phrases\n", n_total, p_total))

# Deterministic target-phrase pick: highest total count. The runner-up
# ties are broken by the natural column order from textir, which is fixed
# across runs.
col_sums <- as.numeric(colSums(counts))
col_means <- as.numeric(colMeans(counts))
target_j <- which.max(col_sums)
target_term <- colnames(counts)[target_j]
cat(sprintf(
  "Target phrase: '%s' (column %d, mean count %.3f, total %d)\n",
  target_term, target_j, col_means[target_j], col_sums[target_j]
))

# Build (X, y): drop the target column from features, use its counts as y.
y <- as.integer(counts[, target_j])
X_raw <- as.matrix(counts[, -target_j])
storage.mode(X_raw) <- "double"
n <- nrow(X_raw)
p <- ncol(X_raw)

# Column standardisation: mean-centre, scale to unit (biased) SD. Matches
# the convention in sim-real-problem.jl exactly.
x_centers <- colMeans(X_raw)
x_scales <- sqrt(colMeans(X_raw * X_raw) - x_centers^2)
x_scales[x_scales == 0] <- 1.0
X <- sweep(X_raw, 2L, x_centers, FUN = "-")
X <- sweep(X, 2L, x_scales, FUN = "/")

# Lambda_max for Poisson with log link at beta = 0, intercept fitted:
#   eta_hat_i = log(ybar); residual r_i = exp(eta_hat_i) - y_i = ybar - y_i
#   gradient w.r.t. beta_j = (1/n) * sum_i X_std[i,j] * r_i
#   = -(1/n) * X_std^T (y - ybar)  (since sum r_i = 0)
# so lambda_max = max_j |X_std^T (y - ybar)|_j / n.
ybar <- mean(y)
v <- y - ybar
lambda_max <- max(abs(as.numeric(t(X) %*% v))) / n
reg <- 0.05
lambda <- reg * lambda_max
cat(sprintf(
  "n = %d, p = %d, ybar = %.4f, lambda_max = %.6g, lambda = %.6g\n",
  n, p, ybar, lambda_max, lambda
))

outdir <- file.path(root, "results", "real-solvers-poisson", "congress109")
dir.create(outdir, recursive = TRUE, showWarnings = FALSE)

# Dense standardised X: gitignored (large), regenerated by this script. y
# and meta.json are small and tracked.
write.table(
  X,
  file = file.path(outdir, "X.csv"),
  sep = ",",
  row.names = FALSE,
  col.names = FALSE
)
write.csv(data.frame(y = y), file.path(outdir, "y.csv"), row.names = FALSE)

meta <- list(
  dataset = "congress109",
  source = "textir::congress109Counts",
  construction = "drop target phrase; regress its count on remaining phrase counts",
  n = n,
  p = p,
  target_phrase = target_term,
  target_column_index_in_original = target_j,
  y_mean = ybar,
  y_var = var(y),
  y_max = max(y),
  y_zero_share = mean(y == 0),
  reg = reg,
  lambda = lambda,
  lambda_max = lambda_max
)

writeLines(
  toJSON(meta, pretty = TRUE, auto_unbox = TRUE),
  file.path(outdir, "meta.json")
)

cat(sprintf("Wrote congress109 problem to %s\n", outdir))
