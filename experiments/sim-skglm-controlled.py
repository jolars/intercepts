"""skglm AndersonCD pre-fix vs post-fix controlled comparison.

Runs the currently-installed skglm against the family of standardized
logistic problems generated by ``sim-skglm-controlled-problem.jl``. The driver
is intended to be invoked twice from ``run-skglm-controlled.sh`` --- once with
skglm checked out at ``b03644fe`` (pre-fix, gradient intercept update;
matches what skglm 0.5 shipped) and once at ``8f9cbd77`` (post-fix, the merge
of PR #337 introducing the Newton intercept update). The script itself is
agnostic to the installed version --- the ``--commit`` argument is recorded
verbatim as a column in the output CSV.

For each cell we record ``n_iter_`` (AndersonCD outer iterations), the
solver's reported stop criterion, the primal objective at termination,
wall-clock runtime, and a ``converged`` flag. ``n_iter_`` is the primary
pass-count metric for the resulting heatmap; the inner CD epoch cap
(``max_epochs``) is held constant across cells and commits.

Output is appended to ``results/skglm-controlled/results.csv`` so two
invocations populate one combined file. Re-running from a clean state
requires deleting that CSV first.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd

from skglm import GeneralizedLinearEstimator
from skglm.datafits import Logistic
from skglm.penalties import L1
from skglm.solvers import AndersonCD


TOL = 1.0e-8
MAX_ITER = 5000
MAX_EPOCHS = 200_000


def logistic_primal(X, y_pm, lam, beta0, beta):
    eta = beta0 + X @ beta
    z = -y_pm * eta
    loss = np.where(z > 0, z + np.log1p(np.exp(-z)), np.log1p(np.exp(z)))
    return loss.mean() + lam * np.abs(beta).sum()


def run_cell(cells_dir: Path, row: pd.Series) -> dict:
    cell_path = cells_dir / row["cell_name"]
    X = pd.read_csv(cell_path / "X.csv", header=None).to_numpy()
    ydf = pd.read_csv(cell_path / "y.csv")
    y_pm = ydf["y_pm"].to_numpy().astype(float)
    meta = json.loads((cell_path / "meta.json").read_text())
    lam = meta["lambda"]

    solver = AndersonCD(
        tol=TOL,
        max_iter=MAX_ITER,
        max_epochs=MAX_EPOCHS,
        fit_intercept=True,
        warm_start=False,
        verbose=0,
    )
    est = GeneralizedLinearEstimator(
        datafit=Logistic(),
        penalty=L1(alpha=lam),
        solver=solver,
    )

    t0 = time.perf_counter()
    est.fit(X, y_pm)
    runtime = time.perf_counter() - t0

    intercept = est.intercept_
    beta0 = float(intercept) if np.ndim(intercept) == 0 else float(intercept[0])
    beta = np.asarray(est.coef_).ravel()
    primal = logistic_primal(X, y_pm, lam, beta0, beta)
    n_iter = int(est.n_iter_) if np.ndim(est.n_iter_) == 0 else int(est.n_iter_[0])
    stop_crit = float(est.stop_crit_)

    return dict(
        cell_id=int(row["cell_id"]),
        cell_name=row["cell_name"],
        mu0=float(row["mu0"]),
        reg=float(row["reg"]),
        seed=int(row["seed"]),
        n=int(row["n"]),
        p=int(row["p"]),
        lambda_=lam,
        n_iter=n_iter,
        stop_crit=stop_crit,
        primal=primal,
        runtime=runtime,
        converged=bool(stop_crit < TOL),
        intercept=beta0,
    )


COLS = [
    "commit",
    "cell_id",
    "cell_name",
    "mu0",
    "reg",
    "seed",
    "n",
    "p",
    "lambda_",
    "n_iter",
    "stop_crit",
    "primal",
    "runtime",
    "converged",
    "intercept",
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--commit",
        required=True,
        help="skglm commit SHA to record alongside the run (does not check out; the shell wrapper handles that)",
    )
    parser.add_argument(
        "--out",
        required=True,
        type=Path,
        help="Output CSV; rows are appended one-per-cell so progress is preserved on early exit",
    )
    parser.add_argument(
        "--index",
        type=Path,
        default=Path(__file__).resolve().parent.parent
        / "results"
        / "skglm-controlled"
        / "index.csv",
    )
    args = parser.parse_args()

    cells_dir = args.index.parent / "cells"
    index = pd.read_csv(args.index)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    write_header = not args.out.exists()

    print(f"=== skglm AndersonCD @ {args.commit} ===", flush=True)
    print(f"  tol={TOL:.0e}  max_iter={MAX_ITER}  max_epochs={MAX_EPOCHS}", flush=True)

    with args.out.open("a") as f:
        if write_header:
            f.write(",".join(COLS) + "\n")
            f.flush()

        for i, row in index.iterrows():
            res = run_cell(cells_dir, row)
            res["commit"] = args.commit
            status = "OK" if res["converged"] else "STALL"
            print(
                f"  [{i + 1:>2}/{len(index)}] {res['cell_name']} "
                f"μ0={res['mu0']:.2f} reg={res['reg']:.3f} seed={res['seed']}  "
                f"n_iter={res['n_iter']:>5}  stop={res['stop_crit']:.2e}  "
                f"primal={res['primal']:.6f}  t={res['runtime']:.2f}s  {status}",
                flush=True,
            )
            pd.DataFrame([res])[COLS].to_csv(f, header=False, index=False)
            f.flush()

    print(f"Wrote {len(index)} rows to {args.out}", flush=True)


if __name__ == "__main__":
    main()
